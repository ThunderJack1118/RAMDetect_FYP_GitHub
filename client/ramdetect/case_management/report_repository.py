def list_repository_reports(
    *,
    username_filter: str | None = None,
    machine_filter: str | None = None,
    limit: int = 2000,
) -> list[dict[str, Any]]:
    """List archived report/export files.

    In strict PTM mode, admin machines read from the central repository API.
    Local/shared-folder sidecar scanning remains as a fallback for development
    and single-machine demonstrations.
    """
    api_rows = _api_list_reports(username_filter=username_filter, machine_filter=machine_filter, limit=limit)
    if api_rows:
        return api_rows[:limit]

    # Strict PTM mode: if the central API/admin token is configured, an empty
    # central result should stay empty. Do not scan/create the legacy local
    # ramdetect_report_repository folder unless fallback is explicitly enabled.
    if repository_api_url() and repository_admin_api_enabled() and not _local_repository_fallback_enabled():
        return []

    root = ensure_repository()
    rows: list[dict[str, Any]] = []
    user_filter_l = (username_filter or "").strip().lower()
    machine_filter_l = (machine_filter or "").strip().lower()

    try:
        sidecars = sorted(
            root.rglob("*.ramdetect.json"),
            key=lambda p: p.stat().st_mtime if p.exists() else 0,
            reverse=True,
        )
    except Exception:
        return rows

    for sidecar in sidecars:
        meta = _read_metadata_sidecar(sidecar)
        if not meta:
            continue

        username = str(meta.get("username") or "unknown")
        machine = str(meta.get("machine_name") or meta.get("machine") or "unknown")
        if user_filter_l and username.lower() != user_filter_l:
            continue
        if machine_filter_l and machine.lower() != machine_filter_l:
            continue

        archive_path = str(meta.get("archive_path") or "")
        if not archive_path:
            continue

        # Prefer the sidecar's path, but tolerate moved repository folders by
        # falling back to the file next to the sidecar.
        candidate = Path(archive_path)
        if not candidate.exists():
            maybe = sidecar.with_name(sidecar.name.removesuffix(".ramdetect.json"))
            if maybe.exists():
                archive_path = str(maybe)

        rows.append({
            "timestamp": str(meta.get("timestamp") or ""),
            "username": username,
            "role": str(meta.get("role") or ""),
            "machine_name": machine,
            "action": str(meta.get("action") or "REPORT_ARCHIVED"),
            "file_name": str(meta.get("file_name") or Path(archive_path).name),
            "file_path": archive_path,
            "report_path": archive_path,
            "file_hash": str(meta.get("sha256") or ""),
            "verdict": str(meta.get("verdict") or "").upper(),
            "details_json": json.dumps({
                "source": "shared_report_repository",
                "repository_root": str(root),
                "original_report_path": meta.get("source_path"),
                "archived_report_path": archive_path,
                "archive_sha256": meta.get("sha256"),
                "archive_size_bytes": meta.get("size_bytes"),
                "metadata_sidecar": str(sidecar),
            }, default=str),
        })
        if len(rows) >= limit:
            break

    return rows

def resolve_existing_report_path(path: str) -> str:
    """Return an existing local report path or a cached central API download."""
    raw = str(path or "").strip()
    if raw.startswith(API_URI_PREFIX):
        return _api_download_to_cache(raw)

    candidate = Path(raw).expanduser()
    if not raw:
        return ""

    try:
        candidate = candidate.resolve()
    except Exception:
        candidate = Path(os.path.abspath(str(candidate)))

    if candidate.exists() and candidate.is_file():
        return str(candidate)
    return ""


def download_report_file(source_path: str, destination_path: str) -> dict[str, Any]:
    """Copy/download a report file from repository/original path to an admin-selected path."""
    raw_source = str(source_path or "").strip()
    if raw_source.startswith(API_URI_PREFIX):
        return _api_download_report(raw_source, destination_path)

    src = resolve_existing_report_path(raw_source)
    if not src:
        return {"success": False, "error": "Report file is not available on this PC, repository, or central PTM API."}

    dest = Path(str(destination_path or "")).expanduser()
    if not str(destination_path or "").strip():
        return {"success": False, "error": "No destination selected."}

    try:
        dest = dest.resolve()
    except Exception:
        dest = Path(os.path.abspath(str(dest)))

    dest.parent.mkdir(parents=True, exist_ok=True)

    # Prevent no-op overwrite problems when user chooses the same file.
    try:
        if Path(src).resolve() == dest.resolve():
            return {
                "success": True,
                "source_path": str(src),
                "destination_path": str(dest),
                "sha256": sha256_file(src),
                "size_bytes": Path(src).stat().st_size,
                "same_file": True,
            }
    except Exception:
        pass

    shutil.copy2(src, dest)
    return {
        "success": True,
        "source_path": str(src),
        "destination_path": str(dest),
        "sha256": sha256_file(dest),
        "size_bytes": dest.stat().st_size,
        "same_file": False,
    }
