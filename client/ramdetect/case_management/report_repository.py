def archive_report_file(
    source_path: str,
    *,
    username: str | None = None,
    role: str | None = None,
    machine_name: str | None = None,
    workstation_id: int | str | None = None,
    action: str | None = None,
    verdict: str | None = None,
    source_report_id: str | None = None,
    source_session_id: str | None = None,
    source_workstation_id: str | None = None,
    source_machine_id: str | None = None,
    source_audit_log_id: str | None = None,
) -> dict[str, Any]:
    """Archive/upload a generated report/export for admin monitoring.

    Strict PTM mode behaviour:
    - If RAMDETECT_REPOSITORY_API_URL and RAMDETECT_REPOSITORY_API_TOKEN are
      configured, upload the original exported file directly to the central PTM
      Repository API first.
    - When that upload succeeds, no permanent local copy is created under
      ``ramdetect_report_repository``. That local folder is only used as a
      fallback/offline archive.
    - If the source file is already inside ``ramdetect_report_repository`` from
      an older run, a successful central upload removes that managed cache copy.

    Local fallback behaviour:
    - If the central API is not configured or upload fails, copy the file into
      the managed local repository and write a sidecar metadata JSON.
    """
    source = Path(str(source_path or "")).expanduser()
    if not str(source_path or "").strip():
        return {"success": False, "error": "empty source path"}

    try:
        source = source.resolve()
    except Exception:
        source = Path(os.path.abspath(str(source)))

    if not source.exists() or not source.is_file():
        return {
            "success": False,
            "error": f"source file not found: {source}",
            "source_path": str(source),
        }

    local_root = repository_root()
    already_in_local_repo = _is_relative_to(source, local_root)
