def metadata_sidecar_path(report_path: str | os.PathLike[str]) -> Path:
    """Return the sidecar metadata path for an archived report/export file."""
    p = Path(report_path)
    return p.with_name(p.name + ".ramdetect.json")


def _write_metadata_sidecar(meta: dict[str, Any]) -> None:
    """Write per-file metadata beside the archived report.

    One sidecar per report avoids JSONL/CSV write conflicts when multiple PCs
    sync to the same Google Drive folder.
    """
    archive_path = str(meta.get("archive_path") or "")
    if not archive_path:
        return
    sidecar = metadata_sidecar_path(archive_path)
    sidecar.parent.mkdir(parents=True, exist_ok=True)
    safe = dict(meta)
    safe["metadata_schema"] = "ramdetect_report_repository_v1"
    safe["metadata_sidecar"] = str(sidecar)
    tmp = sidecar.with_suffix(sidecar.suffix + ".tmp")
    tmp.write_text(json.dumps(safe, indent=2, sort_keys=True, default=str), encoding="utf-8")
    try:
        tmp.replace(sidecar)
    except Exception:
        # Some synced folders may momentarily lock files. Fall back to direct write.
        sidecar.write_text(json.dumps(safe, indent=2, sort_keys=True, default=str), encoding="utf-8")
        try:
            tmp.unlink(missing_ok=True)
        except Exception:
            pass


def _read_metadata_sidecar(path: Path) -> dict[str, Any] | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8", errors="ignore"))
        if isinstance(data, dict):
            return data
    except Exception:
        return None
    return None

def _is_relative_to(path: Path, root: Path) -> bool:
    try:
        path.resolve().relative_to(root.resolve())
        return True
    except Exception:
        return False

def _remove_managed_repository_copy(path: Path, root: Path) -> None:
    """Remove a RAMDetect local repository cache copy after successful PTM upload.

    This only deletes files inside ``ramdetect_report_repository``. It never
    deletes the user's original exported report under reports/, Desktop, or
    Downloads. Empty parent folders are pruned up to the repository root.
    """
    try:
        path = path.resolve()
        root = root.resolve()
        if not _is_relative_to(path, root):
            return
        sidecar = metadata_sidecar_path(path)
        try:
            sidecar.unlink(missing_ok=True)
        except Exception:
            pass
        try:
            path.unlink(missing_ok=True)
        except Exception:
            return
        parent = path.parent
        while parent != root and _is_relative_to(parent, root):
            try:
                parent.rmdir()
            except OSError:
                break
            parent = parent.parent
    except Exception:
        return


