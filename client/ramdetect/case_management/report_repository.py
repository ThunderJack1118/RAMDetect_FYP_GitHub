API_URI_PREFIX = "ramdetect-api://"


def _local_env_value(name: str, default: str = "") -> str:
    """Read RAMDetect_RUNTIME.env beside the installed/source app as a fallback to Windows env."""
    raw = os.environ.get(name)
    if raw not in (None, ""):
        return str(raw).strip()

    candidates = []
    try:
        import sys as _sys
        exe_dir = Path(_sys.executable).resolve().parent
        candidates.append(exe_dir / "RAMDetect_RUNTIME.env")
        candidates.append(exe_dir / "_internal" / "RAMDetect_RUNTIME.env")
    except Exception:
        pass

    try:
        candidates.append(Path.cwd() / "RAMDetect_RUNTIME.env")
    except Exception:
        pass

    try:
        here = Path(__file__).resolve()
        for parent in [here.parent, *here.parents]:
            candidates.append(parent / "RAMDetect_RUNTIME.env")
    except Exception:
        pass

    for env_path in candidates:
        try:
            if not env_path.exists():
                continue
            for line in env_path.read_text(encoding="utf-8", errors="ignore").splitlines():
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                if k.strip() == name:
                    return v.strip().strip('"').strip("'")
        except Exception:
            continue

    return default



def repository_api_url() -> str:
    return _local_env_value("RAMDETECT_REPOSITORY_API_URL", "").strip().rstrip("/")
def repository_api_token(*, admin: bool = False) -> str:
    if admin:
        return _local_env_value("RAMDETECT_REPOSITORY_ADMIN_API_TOKEN", "").strip()
    return _local_env_value("RAMDETECT_REPOSITORY_API_TOKEN", "").strip()
def _offline_local_mode_enabled() -> bool:
    return _local_env_value("RAMDETECT_OFFLINE_LOCAL_MODE", "").strip().lower() in {"1", "true", "yes", "on"}
def repository_api_enabled() -> bool:
    if _offline_local_mode_enabled():
        return False
    return bool(repository_api_url() and repository_api_token(admin=False))


def repository_admin_api_enabled() -> bool:
    if _offline_local_mode_enabled():
        return False
    return bool(repository_api_url() and repository_api_token(admin=True))


def _api_report_uri(report_id: str, file_name: str = "") -> str:
    safe_name = urllib.parse.quote(str(file_name or "report"), safe="")
    return f"{API_URI_PREFIX}{report_id}/{safe_name}"


def _parse_api_report_uri(uri: str) -> tuple[str, str]:
    raw = str(uri or "")
    if not raw.startswith(API_URI_PREFIX):
        return "", ""
    tail = raw[len(API_URI_PREFIX):]
    if "/" in tail:
        report_id, encoded_name = tail.split("/", 1)
        return report_id.strip(), urllib.parse.unquote(encoded_name)
    return tail.strip(), ""


def _api_json_request(path: str, *, token: str, query: dict[str, Any] | None = None) -> dict[str, Any]:
    base = repository_api_url()
    if not base:
        return {"success": False, "error": "RAMDETECT_REPOSITORY_API_URL is not configured"}
    url = base + path
    if query:
        url += "?" + urllib.parse.urlencode({k: v for k, v in query.items() if v not in (None, "")})
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {token}"})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            payload = resp.read().decode("utf-8", errors="replace")
            return json.loads(payload) if payload else {"success": True}
    except urllib.error.HTTPError as exc:
        try:
            err = exc.read().decode("utf-8", errors="replace")
        except Exception:
            err = str(exc)
        return {"success": False, "error": f"HTTP {exc.code}: {err}"}
    except Exception as exc:
        return {"success": False, "error": str(exc)}


def _api_upload_report_file(path: Path, meta: dict[str, Any]) -> dict[str, Any]:
    """Upload an archived report/export to the central PTM repository API.

    Uses stdlib urllib to avoid adding client-side dependencies. Intended for
    generated reports/exports only, not raw RAM dumps.
    """
    if not repository_api_enabled():
        return {"success": False, "error": "central repository API not configured"}
    if not path.exists() or not path.is_file():
        return {"success": False, "error": "archive file not found for API upload"}

    boundary = "----RAMDetectBoundary" + hashlib.sha256(os.urandom(16)).hexdigest()
    fields = {
        "username": meta.get("username") or "unknown",
        "role": meta.get("role") or "unknown",
        "machine_name": meta.get("machine_name") or "unknown",
        "workstation_id": meta.get("workstation_id") or "",
        "action": meta.get("action") or "REPORT_ARCHIVED",
        "verdict": str(meta.get("verdict") or "").upper(),
        "original_path": meta.get("source_path") or "",
        "file_hash": meta.get("sha256") or sha256_file(path),
        "details_json": json.dumps({
            "client_repository_root": meta.get("repository_root"),
            "client_archive_path": meta.get("archive_path"),
            "original_report_path": meta.get("source_path"),
            "already_archived": meta.get("already_archived", False),
            "source_report_id": meta.get("source_report_id"),
            "source_session_id": meta.get("source_session_id"),
            "source_workstation_id": meta.get("source_workstation_id"),
            "source_machine_id": meta.get("source_machine_id"),
            "source_audit_log_id": meta.get("source_audit_log_id"),
        }, default=str),
        "source_report_id": meta.get("source_report_id") or "",
        "source_session_id": meta.get("source_session_id") or "",
        "source_workstation_id": meta.get("source_workstation_id") or "",
        "source_machine_id": meta.get("source_machine_id") or "",
        "source_audit_log_id": meta.get("source_audit_log_id") or "",
    }

    body = bytearray()
    for name, value in fields.items():
        body.extend(f"--{boundary}\r\n".encode())
        body.extend(f'Content-Disposition: form-data; name="{name}"\r\n\r\n'.encode())
        body.extend(str(value).encode("utf-8"))
        body.extend(b"\r\n")

    filename = path.name
    body.extend(f"--{boundary}\r\n".encode())
    body.extend(f'Content-Disposition: form-data; name="file"; filename="{filename}"\r\n'.encode())
    body.extend(b"Content-Type: application/octet-stream\r\n\r\n")
    body.extend(path.read_bytes())
    body.extend(b"\r\n")
    body.extend(f"--{boundary}--\r\n".encode())

    req = urllib.request.Request(
        repository_api_url() + "/api/v1/reports/upload",
        data=bytes(body),
        method="POST",
        headers={
            "Authorization": f"Bearer {repository_api_token(admin=False)}",
            "Content-Type": f"multipart/form-data; boundary={boundary}",
            "Content-Length": str(len(body)),
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            payload = resp.read().decode("utf-8", errors="replace")
            data = json.loads(payload) if payload else {"success": True}
            if data.get("success") and data.get("id"):
                data["api_uri"] = _api_report_uri(str(data.get("id")), filename)
            return data
    except urllib.error.HTTPError as exc:
        try:
            err = exc.read().decode("utf-8", errors="replace")
        except Exception:
            err = str(exc)
        return {"success": False, "error": f"HTTP {exc.code}: {err}"}
    except Exception as exc:
        return {"success": False, "error": str(exc)}


def _api_list_reports(username_filter: str | None = None, machine_filter: str | None = None, limit: int = 2000) -> list[dict[str, Any]]:
    if not repository_admin_api_enabled():
        return []
