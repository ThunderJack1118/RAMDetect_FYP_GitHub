"""
report_repository.py
--------------------
Managed report repository for RAMDetect Activity/Admin monitoring.

Purpose
-------
This module copies report/export files generated by different RAMDetect users
and workstations into one controlled repository folder. Admin users can then
open/download those archived files from Activity Monitor without depending on
the original user's Desktop/Downloads path.

Default repository folder
-------------------------
Project root:
    ramdetect_report_repository/

Override with environment variable:
    RAMDETECT_REPORT_REPOSITORY=C:\\RAMDetect_Report_Repository

Google Drive shared repository mode
-----------------------------------
Install Google Drive for desktop and set RAMDETECT_REPORT_REPOSITORY to the
local synced Google Drive folder, for example:
    G:\\Shared drives\\RAMDetect-ReportRepository

Each archived file also gets a sidecar metadata JSON:
    <archived_report>.ramdetect.json

This allows an admin workstation to scan the shared repository and list reports
created by other RAMDetect users/workstations even when their local SQLite
audit databases are not shared.

This module is monitoring/report-storage only. It does not touch parser output,
FeatureMapper, Autoencoder MSE fusion, RF threshold, or ML verdict logic.
"""

