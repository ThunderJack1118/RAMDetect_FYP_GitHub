def _project_root() -> Path:
    # __file__ = <project>/ramdetect/case_management/report_repository.py
    return Path(__file__).resolve().parents[2]


def repository_root() -> Path:
    configured = os.environ.get("RAMDETECT_REPORT_REPOSITORY", "").strip()
    root = Path(configured).expanduser() if configured else (_project_root() / "ramdetect_report_repository")
    return root.resolve()


def _local_repository_fallback_enabled() -> bool:
    """Return True only when the legacy local report repository is allowed.

    Strict PTM deployment uses the central PTM Repository API as the
    authoritative shared source. In that mode, RAMDetect should not even
    recreate the empty local ``ramdetect_report_repository`` folder with
    README.md/.gitkeep.

    Local fallback remains available for offline/single-PC testing by setting:
        RAMDETECT_ENABLE_LOCAL_REPORT_REPOSITORY_FALLBACK=1
    """
    api_configured = bool(
        repository_api_url()
        and (repository_api_token(admin=False) or repository_api_token(admin=True))
    )
    if not api_configured:
        return True

    value = os.environ.get("RAMDETECT_ENABLE_LOCAL_REPORT_REPOSITORY_FALLBACK", "0").strip().lower()
    return value in {"1", "true", "yes", "on"}


def ensure_repository() -> Path:
    root = repository_root()

    # In strict PTM mode, local fallback is disabled. Return the path for
    # compatibility, but do not create the folder, README.md, or .gitkeep.
    if not _local_repository_fallback_enabled():
        return root

    root.mkdir(parents=True, exist_ok=True)

    readme = root / "README.md"
    if not readme.exists():
        readme.write_text(
            "# RAMDetect Report Repository\n\n"
            "This folder stores archived copies of reports and exported workbooks generated by RAMDetect users/workstations.\n\n"
            "Purpose: allow Admin users to review and download report files from Activity Monitor/Admin monitoring.\n\n"
            "Do not store live malware samples or raw RAM dumps here. This repository is for generated reports/exports only.\n",
            encoding="utf-8",
        )

    keep = root / ".gitkeep"
    if not keep.exists():
        keep.write_text("", encoding="utf-8")

    return root


def _safe_part(value: Any, default: str = "unknown", max_len: int = 80) -> str:
    text = str(value or "").strip() or default
    text = re.sub(r"[^A-Za-z0-9_.-]+", "_", text)
    text = text.strip("._-") or default
    try:
        max_len = int(max_len)
    except Exception:
        max_len = 80
    max_len = max(16, min(max_len, 220))
    return text[:max_len]


def sha256_file(path: str | os.PathLike[str]) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()





